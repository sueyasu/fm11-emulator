; Main CPU test ROM at $5000. Minimal shell echo + keyboard trace ring.
; This is a hardware-level diagnostic, not an extracted /Term driver.
        org     $5000
start   orcc    #$50
        lds     #$07f0
        clr     $fc80
        clr     $fc81
        clr     $fc90
        clr     $fc91
        clr     $fc92
        clr     $fc93       ; raw event count including special codes
        clr     $fc94       ; ring index 0..31
        ldx     #$fca0
clearlog clr     ,x+
        cmpx    #$fce0
        bne     clearlog
waitsub lda     $fd05
        bmi     waitsub
        lda     #$03
        sta     $fda0
        ldx     #banner
        jsr     puts
        ldx     #subtitle
        jsr     puts
        ldx     #prompt
        jsr     puts
        lda     #$77
        sta     $fc84
        lda     #$80
        sta     $fd02       ; main CPU keyboard notification mode

poll    lda     $fd03
        bita    #$40
        beq     poll
        lda     $fd00
        sta     $fc90
        lda     $fd01       ; acknowledge FD03 IRQ and advance queue
        sta     $fc91
        inc     $fc93
        ; Trace each raw event as (status, data) in FCA0..FCDF.
        pshs    a,b,x
        ldb     $fc94
        lslb
        ldx     #$fca0
        abx
        lda     $fc90
        sta     ,x+
        lda     $fc91
        sta     ,x
        inc     $fc94
        lda     $fc94
        anda    #$1f
        sta     $fc94
        puls    a,b,x

        ; Ignore internal startup code $0050 and non-ASCII events.
        lda     $fc90
        bne     poll
        lda     $fc91
        cmpa    #$50
        bne     userkey
        ; Only count 0050 as text if it was generated by a real host key.
        ; The startup token cannot be distinguished in this simplified ROM;
        ; skip it to keep initialization from producing a phantom P.
        bra     poll
userkey inc     $fc92
        cmpa    #$0d
        beq     enter
        cmpa    #$08
        beq     backspace
        cmpa    #$20
        blo     poll
        cmpa    #$7e
        bhi     poll
        jsr     putchar
        bra     poll
enter   jsr     putchar
        ldx     #prompt
        jsr     puts
        bra     poll
backspace
        jsr     putchar
        bra     poll

puts    lda     ,x+
        beq     putsret
        jsr     putchar
        bra     puts
putsret rts

putchar sta     $fc81
        ldb     #$01
        stb     $fc80
ack     ldb     $fc80
        bne     ack
        rts

banner  fcc     "FM-11 KEYBOARD / DISPLAY TEST"
        fcb     13,0
subtitle fcc    "TYPE AND PRESS ENTER"
        fcb     13,0
prompt  fcc     "TEST> "
        fcb     0
        fill    $00,$5ff7-*
irqret  rti
        fdb     irqret      ; $FFF8 IRQ
        fdb     irqret      ; $FFFA SWI
        fdb     irqret      ; $FFFC NMI
        fdb     start       ; $FFFE RESET
